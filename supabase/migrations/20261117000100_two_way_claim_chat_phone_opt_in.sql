CREATE OR REPLACE FUNCTION public.api_report_claims(p_token text, p_report_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id bigint;
  v_result jsonb;
BEGIN
  v_user_id := nullif(public.api_me(p_token)::jsonb #>> '{user,id}', '')::bigint;
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'Sesi tidak valid.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.reports r WHERE r.id = p_report_id AND r.owner_id = v_user_id) THEN
    RAISE EXCEPTION 'Anda tidak memiliki akses ke klaim laporan ini.';
  END IF;

  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'id', c.id, 'report_id', c.report_id, 'claimant_id', c.claimant_id,
    'claimant_name', u.name, 'status', c.status, 'message', c.message,
    'submitted_at', c.submitted_at,
    'claimant_share_phone', coalesce(c.claimant_share_phone, false),
    'owner_share_phone', coalesce(c.owner_share_phone, false)
  ) ORDER BY c.submitted_at DESC, c.id DESC), '[]'::jsonb)
  INTO v_result
  FROM public.claims c
  JOIN public.users u ON u.id = c.claimant_id
  WHERE c.report_id = p_report_id;
  RETURN jsonb_build_object('claims', v_result);
END;
$$;

CREATE OR REPLACE FUNCTION public.api_decide_claim(p_token text, p_claim_id bigint, p_decision text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id bigint;
  v_claim public.claims%ROWTYPE;
  v_status text;
BEGIN
  v_user_id := nullif(public.api_me(p_token)::jsonb #>> '{user,id}', '')::bigint;
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'Sesi tidak valid.'; END IF;
  IF p_decision IS NULL OR p_decision NOT IN ('approved', 'rejected') THEN RAISE EXCEPTION 'Keputusan klaim tidak valid.'; END IF;

  SELECT c.* INTO v_claim
  FROM public.claims c
  JOIN public.reports r ON r.id = c.report_id
  WHERE c.id = p_claim_id AND r.owner_id = v_user_id
  FOR UPDATE OF c;
  IF NOT FOUND THEN RAISE EXCEPTION 'Klaim tidak ditemukan atau Anda bukan pemilik laporan.'; END IF;
  IF v_claim.status <> 'pending' THEN RAISE EXCEPTION 'Klaim ini sudah diputuskan.'; END IF;

  UPDATE public.claims SET status = p_decision WHERE id = p_claim_id;
  v_status := CASE WHEN p_decision = 'approved' THEN 'Sudah dikembalikan' ELSE 'Menunggu pemilik' END;
  UPDATE public.reports SET status = v_status WHERE id = v_claim.report_id;
  RETURN jsonb_build_object('claim_id', p_claim_id, 'status', p_decision, 'report_status', v_status);
END;
$$;

CREATE OR REPLACE FUNCTION public.api_claim_detail(p_token text, p_claim_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id bigint;
  v_result jsonb;
BEGIN
  v_user_id := nullif(public.api_me(p_token)::jsonb #>> '{user,id}', '')::bigint;
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'Sesi tidak valid.'; END IF;

  SELECT jsonb_build_object(
    'id', c.id, 'report_id', c.report_id, 'claimant_id', c.claimant_id,
    'claimant_name', claimant.name, 'owner_id', r.owner_id, 'owner_name', owner_user.name,
    'report_title', r.title, 'report_category', r.category, 'report_location', r.location,
    'report_status', r.status, 'status', c.status, 'proof', c.message,
    'submitted_at', c.submitted_at,
    'is_owner', (r.owner_id = v_user_id),
    'claimant_share_phone', coalesce(c.claimant_share_phone, false),
    'owner_share_phone', coalesce(c.owner_share_phone, false),
    'owner_phone', CASE WHEN c.claimant_share_phone AND c.owner_share_phone
      THEN coalesce(to_jsonb(owner_user)->>'phone', to_jsonb(owner_user)->>'phone_number') ELSE NULL END,
    'claimant_phone', CASE WHEN c.claimant_share_phone AND c.owner_share_phone
      THEN coalesce(to_jsonb(claimant)->>'phone', to_jsonb(claimant)->>'phone_number') ELSE NULL END
  ) INTO v_result
  FROM public.claims c
  JOIN public.reports r ON r.id = c.report_id
  JOIN public.users claimant ON claimant.id = c.claimant_id
  JOIN public.users owner_user ON owner_user.id = r.owner_id
  WHERE c.id = p_claim_id AND v_user_id IN (c.claimant_id, r.owner_id);
  IF v_result IS NULL THEN RAISE EXCEPTION 'Klaim tidak ditemukan atau Anda bukan pihak terkait.'; END IF;
  RETURN jsonb_build_object('claim', v_result);
END;
$$;

CREATE OR REPLACE FUNCTION public.api_claim_messages(p_token text, p_claim_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id bigint;
  v_messages jsonb;
BEGIN
  v_user_id := nullif(public.api_me(p_token)::jsonb #>> '{user,id}', '')::bigint;
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'Sesi tidak valid.'; END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.claims c JOIN public.reports r ON r.id = c.report_id
    WHERE c.id = p_claim_id AND v_user_id IN (c.claimant_id, r.owner_id)
  ) THEN RAISE EXCEPTION 'Klaim tidak ditemukan atau Anda bukan pihak terkait.'; END IF;

  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'id', m.id, 'claim_id', m.claim_id, 'sender_id', m.sender_id,
    'sender_name', u.name, 'message', m.message, 'created_at', m.created_at
  ) ORDER BY m.created_at, m.id), '[]'::jsonb)
  INTO v_messages
  FROM public.claim_messages m JOIN public.users u ON u.id = m.sender_id
  WHERE m.claim_id = p_claim_id;
  RETURN jsonb_build_object('messages', v_messages);
END;
$$;

CREATE OR REPLACE FUNCTION public.api_send_claim_message(p_token text, p_claim_id bigint, p_message text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id bigint;
  v_message_id bigint;
  v_message text := btrim(coalesce(p_message, ''));
  v_created_at timestamptz;
BEGIN
  v_user_id := nullif(public.api_me(p_token)::jsonb #>> '{user,id}', '')::bigint;
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'Sesi tidak valid.'; END IF;
  IF length(v_message) NOT BETWEEN 1 AND 2000 THEN RAISE EXCEPTION 'Pesan harus berisi 1 sampai 2000 karakter.'; END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.claims c JOIN public.reports r ON r.id = c.report_id
    WHERE c.id = p_claim_id AND v_user_id IN (c.claimant_id, r.owner_id)
  ) THEN RAISE EXCEPTION 'Klaim tidak ditemukan atau Anda bukan pihak terkait.'; END IF;

  INSERT INTO public.claim_messages (claim_id, sender_id, message)
  VALUES (p_claim_id, v_user_id, v_message)
  RETURNING id, created_at INTO v_message_id, v_created_at;
  RETURN jsonb_build_object('message', jsonb_build_object(
    'id', v_message_id, 'claim_id', p_claim_id, 'sender_id', v_user_id,
    'message', v_message, 'created_at', v_created_at
  ));
END;
$$;

CREATE OR REPLACE FUNCTION public.api_toggle_phone_share(p_token text, p_claim_id bigint, p_agree boolean)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id bigint;
  v_claim public.claims%ROWTYPE;
  v_owner_id bigint;
  v_mutual boolean;
  v_owner_phone text;
  v_claimant_phone text;
BEGIN
  v_user_id := nullif(public.api_me(p_token)::jsonb #>> '{user,id}', '')::bigint;
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'Sesi tidak valid.'; END IF;

  SELECT c.* INTO v_claim
  FROM public.claims c JOIN public.reports r ON r.id = c.report_id
  WHERE c.id = p_claim_id AND v_user_id IN (c.claimant_id, r.owner_id)
  FOR UPDATE OF c;
  IF NOT FOUND THEN RAISE EXCEPTION 'Klaim tidak ditemukan atau Anda bukan pihak terkait.'; END IF;
  SELECT r.owner_id INTO v_owner_id FROM public.reports r WHERE r.id = v_claim.report_id;

  IF v_user_id = v_claim.claimant_id THEN
    UPDATE public.claims SET claimant_share_phone = coalesce(p_agree, false) WHERE id = p_claim_id
    RETURNING * INTO v_claim;
  ELSE
    UPDATE public.claims SET owner_share_phone = coalesce(p_agree, false) WHERE id = p_claim_id
    RETURNING * INTO v_claim;
  END IF;

  v_mutual := v_claim.claimant_share_phone AND v_claim.owner_share_phone;
  IF v_mutual THEN
    SELECT coalesce(to_jsonb(owner_user)->>'phone', to_jsonb(owner_user)->>'phone_number'),
           coalesce(to_jsonb(claimant)->>'phone', to_jsonb(claimant)->>'phone_number')
      INTO v_owner_phone, v_claimant_phone
    FROM public.users owner_user, public.users claimant
    WHERE owner_user.id = v_owner_id AND claimant.id = v_claim.claimant_id;
  END IF;
  RETURN jsonb_build_object(
    'claimant_share_phone', v_claim.claimant_share_phone,
    'owner_share_phone', v_claim.owner_share_phone,
    'mutual_consent', v_mutual,
    'owner_phone', CASE WHEN v_mutual THEN v_owner_phone ELSE NULL END,
    'claimant_phone', CASE WHEN v_mutual THEN v_claimant_phone ELSE NULL END
  );
END;
$$;

