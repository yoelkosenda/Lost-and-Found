-- Tabel riwayat perubahan status laporan (Timeline)
CREATE TABLE IF NOT EXISTS public.report_status_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id bigint NOT NULL REFERENCES public.reports(id) ON DELETE CASCADE,
  status text NOT NULL,
  note text NOT NULL DEFAULT '',
  changed_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS report_status_history_report_created_idx
  ON public.report_status_history (report_id, created_at, id);

ALTER TABLE public.report_status_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.report_status_history FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.report_status_history_id_seq FROM anon, authenticated;

-- Fungsi trigger untuk mencatat status awal dan setiap perubahan status pada public.reports
CREATE OR REPLACE FUNCTION public.log_report_status_history()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.report_status_history (report_id, status, note, changed_by, created_at)
    VALUES (NEW.id, NEW.status, 'Laporan dibuat', NEW.owner_id, now());
  ELSIF TG_OP = 'UPDATE' AND NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO public.report_status_history (report_id, status, note, changed_by, created_at)
    VALUES (
      NEW.id,
      NEW.status,
      'Status diperbarui dari "' || OLD.status || '" menjadi "' || NEW.status || '"',
      NEW.owner_id,
      now()
    );
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_reports_status_history ON public.reports;
CREATE TRIGGER trg_reports_status_history
  AFTER INSERT OR UPDATE OF status ON public.reports
  FOR EACH ROW
  EXECUTE FUNCTION public.log_report_status_history();

-- Backfill riwayat awal untuk laporan yang sudah ada sebelum migrasi ini
INSERT INTO public.report_status_history (report_id, status, note, changed_by, created_at)
SELECT
  r.id,
  r.status,
  'Laporan dibuat',
  r.owner_id,
  coalesce(r.reported_at::timestamptz, now())
FROM public.reports r
WHERE NOT EXISTS (
  SELECT 1 FROM public.report_status_history h WHERE h.report_id = r.id
);

-- RPC untuk mengambil riwayat status sebuah laporan
CREATE OR REPLACE FUNCTION public.api_report_history(p_token text, p_report_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id bigint;
  v_history jsonb;
BEGIN
  v_user_id := nullif(public.api_me(p_token)::jsonb #>> '{user,id}', '')::bigint;
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Sesi Anda telah berakhir. Silakan masuk kembali.';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.reports r WHERE r.id = p_report_id) THEN
    RAISE EXCEPTION 'Laporan tidak ditemukan.';
  END IF;

  SELECT coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', h.id,
        'report_id', h.report_id,
        'status', h.status,
        'note', h.note,
        'changed_by', h.changed_by,
        'changed_by_name', coalesce(u.name, 'Sistem'),
        'created_at', h.created_at
      )
      ORDER BY h.created_at ASC, h.id ASC
    ),
    '[]'::jsonb
  )
  INTO v_history
  FROM public.report_status_history h
  LEFT JOIN public.users u ON u.id = h.changed_by
  WHERE h.report_id = p_report_id;

  RETURN jsonb_build_object('history', v_history);
END;
$$;

REVOKE ALL ON FUNCTION public.api_report_history(text, bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.api_report_history(text, bigint) TO anon, authenticated;

